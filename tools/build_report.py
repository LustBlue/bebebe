    report.add_paragraph("", indent=0)
    report.add_paragraph(f"Период прохождения практики: {data['period']}",
                         align="center", indent=0)
    for _ in range(3):
        report.add_paragraph("", indent=0)

    table = report.document.add_table(rows=5, cols=2)
    rows = (
        ("Обучающийся", "_____________________   _____________"),
        ("Группа", "_____________"),
        ("Руководитель практики", "_____________________   _____________"),
        ("Оценка", "_____________"),
        ("Дата", "«____» ______________ 2026 г."),
    )
    for index, (label, value) in enumerate(rows):
        cells = table.rows[index].cells
        for cell, text in zip(cells, (label, value)):
            paragraph = cell.paragraphs[0]
            paragraph.paragraph_format.first_line_indent = Cm(0)
            paragraph.paragraph_format.line_spacing = 1.5
            run = paragraph.add_run(text)
            run.font.name = "Times New Roman"
            run.font.size = Pt(12)
    for column, width in zip(table.columns, (Cm(5.0), Cm(7.5))):
        column.width = width

    for _ in range(2):
        report.add_paragraph("", indent=0)
    report.add_paragraph(data["city_year"], align="center", indent=0)


