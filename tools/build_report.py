def _read(path: Path) -> str:
    """Прочитать текстовый файл, если он существует."""
    return path.read_text(encoding="utf-8") if path.exists() else ""


def _count_tests() -> tuple[int, dict[str, int]]:
    """Подсчитать число автоматических тестов в наборе.

    :return: пара (общее число тестов, распределение по тестовым модулям)
    """
    counters: dict[str, int] = {}
    total = 0
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        matches = re.findall(r"^def (test_[a-zA-Z0-9_]+)", path.read_text(encoding="utf-8"),
                             flags=re.MULTILINE)
        counters[path.stem] = len(matches)
        total += len(matches)
    return total, counters


def _count_lines() -> tuple[int, int, int]:
    """Подсчитать строки исходного кода, тестов и документации."""
    def count(directory: Path) -> int:
        return sum(len(p.read_text(encoding="utf-8").splitlines())
                   for p in directory.rglob("*.py") if "__pycache__" not in p.parts)

    return count(ROOT / "src"), count(ROOT / "tests"), count(ROOT / "tools")


