def build(output: Path) -> Path:
    """Собрать итоговый отчёт о практике.

    :param output: путь к создаваемому файлу DOCX
    :return: путь к созданному файлу
    """
    total_tests, by_module = _count_tests()
    src_lines, test_lines, tool_lines = _count_lines()
    _total, module_count, integration_count = 0, 0, 0
    for name, count in by_module.items():
        if name == "test_integration":
            integration_count += count
        else:
            module_count += count

    stats = {
        "tests": total_tests,
        "by_module": by_module,
        "module_tests": module_count,
        "integration_tests": integration_count,
        "src_lines": src_lines,
        "test_lines": test_lines,
        "tool_lines": tool_lines,
        "transitions": 8,
        "transition_coverage": 100,
        "scenarios": _count_scenarios(),
        "requirements": _count_requirements(),
    }

    report = DocxReport(title="Отчёт о производственной практике ПП.02")
    title_page(report)
    # Титульный лист не нумеруется; нумерация начинается со следующей страницы
    report.start_numbering(start_at=2)
    introduction(report, stats)
    diary(report)
    section_technology(report, stats)
    section_tools(report, stats)
    section_models(report, stats)
    conclusion(report, stats)
    sources(report)
    appendix_a_code(report)
    appendix_b_requirements(report)
    appendix_c_tests(report, stats)
    appendix_d_inspection(report)
    appendix_e_diagrams(report)
    appendix_f_screenshots(report)

    return report.save(output)


def _count_scenarios() -> int:
    """Подсчитать число тестовых сценариев в документе сценариев."""
    path = ROOT / "docs" / "test_scenarios.md"
    if not path.exists():
        return 0
    content = path.read_text(encoding="utf-8")
    return len(re.findall(r"\|\s*TC-[0-9A-Za-z.-]+", content))


def _count_requirements() -> int:
    """Подсчитать число требований в документе требований."""
    path = ROOT / "docs" / "requirements.md"
    if not path.exists():
        return 0
    content = path.read_text(encoding="utf-8")
    identifiers = set(re.findall(r"((?:FR|NFR)-[A-ZА-Яа-я]{0,3}-?\d+)", content))
    return len(identifiers)


def main(argv: list[str] | None = None) -> int:
    """Точка входа генератора отчёта."""
    parser = argparse.ArgumentParser(description="Сборка отчёта о практике в формате DOCX")
    parser.add_argument("--output", default="docs/Отчёт_производственная_практика_ПП02.docx",
                        help="путь к создаваемому файлу")
    args = parser.parse_args(argv)

    target = Path(args.output)
    if not target.is_absolute():
        target = ROOT / target

    path = build(target)
    size_kb = path.stat().st_size / 1024
    print(f"Отчёт сформирован: {path}")
    print(f"Размер файла: {size_kb:.1f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
