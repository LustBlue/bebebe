def _count_code() -> dict[str, int]:
    """Подсчитать объём исходного кода проекта.

    :return: словарь с числом строк по каталогам и общим количеством тестов
    """
    def count(directory: Path) -> int:
        """Вернуть суммарное число строк в модулях каталога."""
        return sum(len(path.read_text(encoding="utf-8").splitlines())
                   for path in directory.rglob("*.py")
                   if "__pycache__" not in path.parts)

    tests = sorted((ROOT / "tests").glob("test_*.py"))
    test_functions = sum(
        len(re.findall(r"^def (test_[a-zA-Z0-9_]+)", path.read_text(encoding="utf-8"),
                       flags=re.MULTILINE))
        for path in tests
    )

    return {
        "src": count(ROOT / "src"),
        "tests": count(ROOT / "tests"),
        "tools": count(ROOT / "tools"),
        "test_files": len(tests),
        "test_functions": test_functions,
        "tools_count": len(list((ROOT / "tools").glob("*.py"))),
    }


