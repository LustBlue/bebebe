def build(output: Path) -> Path:
    """Собрать отчёт о выполненных работах.

    :param output: путь к создаваемому файлу DOCX
    :return: путь к созданному файлу
    """
    stats = _count_code()

    report = DocxReport(title="Отчёт о выполненных работах по проекту ProjectFlow")
    title_page(report, stats)
    report.start_numbering(start_at=2)
    introduction(report)
    section_tasks(report)
    section_tools(report, stats)
    section_verification(report)
    section_criteria(report)
    conclusion(report, stats)

    return report.save(output)


def main(argv: list[str] | None = None) -> int:
    """Точка входа формирования отчёта о работах."""
    parser = argparse.ArgumentParser(
        description="Сборка отчёта о выполненных работах по проекту ProjectFlow")
    parser.add_argument("--output",
                        default="docs/Отчёт_о_работе_над_ProjectFlow.docx",
                        help="путь к создаваемому файлу")
    args = parser.parse_args(argv)

    target = Path(args.output)
    if not target.is_absolute():
        target = ROOT / target

    path = build(target)
    print(f"Отчёт о работах сформирован: {path}")
    print(f"Размер файла: {path.stat().st_size / 1024:.1f} КБ")
    return 0


