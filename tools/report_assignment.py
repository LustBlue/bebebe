def render(report: "DocxReport") -> None:
    """Добавить раздел «Индивидуальное задание» в отчёт.

    :param report: построитель документа Word
    """
    report.add_heading("ИНДИВИДУАЛЬНОЕ ЗАДАНИЕ", level=1)

    report.add_paragraph(
        "Задание на производственную практику ПП.02 (приводится полностью)."
    )
    report.add_paragraph("Тема задания:", indent=0, bold=True)
    report.add_paragraph(TOPIC, align="center")
    report.add_paragraph("Цель:", indent=0, bold=True)
    report.add_paragraph(GOAL)

    report.add_heading("Общие требования", level=2, align="left")
    report.add_list(REQUIREMENTS)

    report.add_heading("Задачи практики", level=2, align="left")
    for number, title, items, result in TASKS:
        report.add_heading(f"{number}. {title}", level=3, align="left")
        report.add_list(items)
        report.add_paragraph(f"Результат: {result}.")

    report.add_heading("Содержание отчёта", level=2, align="left")
    report.add_list(REPORT_PARTS)
    report.add_paragraph("Приложения:", indent=0)
    report.add_list(APPENDICES)

    report.add_heading("Критерии оценки", level=2, align="left")
    report.add_table(
        ["Критерий", "Баллы"],
        CRITERIA,
        caption="Критерии оценки результатов практики",
        widths=[9.0, 2.0],
    )
    report.add_list(GRADES)

    report.add_paragraph(
        "Задание получено и выполнено в полном объёме. Отчёт составлен в "
        "соответствии с перечисленным содержанием: результаты по каждой "
        "задаче приведены в соответствующих разделах и приложениях."
    )
